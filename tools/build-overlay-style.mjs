/** Keep the synchronous content-script stylesheet in sync with its CSS source. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const css = fs.readFileSync(path.join(root, 'extension/content/overlay.css'), 'utf8');
const text = '// Generated by node tools/build-overlay-style.mjs. Edit overlay.css.\n' +
  '(function(AD){AD.OVERLAY_CSS=' + JSON.stringify(css) + ';})(globalThis.AD=globalThis.AD||{});\n';
const output = path.join(root, 'extension/content/overlay-style.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== text) throw new Error('Run node tools/build-overlay-style.mjs after editing overlay.css');
  console.log('Synchronous overlay stylesheet is up to date.');
} else fs.writeFileSync(output, text);
